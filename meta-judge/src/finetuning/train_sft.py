"""
SFT distillation script: train a smaller model to reproduce outputs
generated by a larger teacher model.

Loads teacher-generated datasets from one or more data source directories
(e.g. damaged_datasets_reasoning/, damaged_datasets_reasoning_sample/) and
trains the student to produce the same output given (input, damage_level).

Usage:
    python train_sft.py --dataset rose --teacher_model llama70b --prompt_type few_shot --exclude_splits=rose_cnndm_validation
    python train_sft.py --dataset rose --data_sources reasoning,reasoning_sample  # combine two sources
    python train_sft.py --dataset cus_qa --teacher_model llama70b --exclude_splits=qa_cz_en
    python train_sft.py --config trained_models/rose/.../run_config.json
"""

