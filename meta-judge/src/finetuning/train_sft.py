DATA_SOURCE_ALIASES = {
    "reasoning":        "damaged_datasets_reasoning",
    "reasoning_sample": "damaged_datasets_reasoning_sample",
    "no_reasoning":     "damaged_datasets",
    "fixed":            "damaged_datasets_fixed",
    "wmt_extra":        "damaged_datasets_wmt",
}

DEFAULT_DATA_SOURCES = ["no_reasoning"]


